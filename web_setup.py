"""Web setup helpers for Save-Restricted-Bot.

This module keeps the Flask setup routes small and provides an in-memory
state machine for Telegram user authorization.  Pyrogram is imported lazily
so the web UI can still import cleanly in environments where the bot
dependencies are not installed yet.
"""

import json
import os
import threading
import time
import uuid
import asyncio
from typing import Any, Dict, Optional


BASE_DIR = os.path.abspath(os.path.dirname(__file__))
DATA_DIR = os.environ.get("DATA_DIR", os.path.join(BASE_DIR, "data"))
CONFIG_DIR = os.path.join(DATA_DIR, "config")
CONFIG_FILE = os.path.join(CONFIG_DIR, "config.json")
ENV_FILE = os.path.join(BASE_DIR, ".env")
SESSION_DIR = os.path.join(DATA_DIR, "auth_sessions")

_setup_states: Dict[str, Dict[str, Any]] = {}
_setup_lock = threading.Lock()


def _ensure_event_loop() -> None:
    """Ensure the current worker thread has an asyncio event loop.

    Pyrogram's synchronous client can be called from Flask worker threads,
    but those threads do not have a current event loop by default.  This
    helper creates and binds one before any Pyrogram network call.
    """
    try:
        asyncio.get_event_loop()
    except RuntimeError:
        asyncio.set_event_loop(asyncio.new_event_loop())


def _ensure_dirs() -> None:
    os.makedirs(CONFIG_DIR, exist_ok=True)
    os.makedirs(SESSION_DIR, exist_ok=True)


def _remove_session_files(session_name: str) -> None:
    """Remove Pyrogram file-session artifacts for a temporary auth session."""
    for suffix in ("", "-journal"):
        path = os.path.join(SESSION_DIR, f"{session_name}.session{suffix}")
        try:
            if os.path.exists(path):
                os.remove(path)
        except OSError:
            pass


def _disconnect_auth_client(client: Any) -> None:
    """Disconnect a temporary auth client without requiring initialization."""
    if client is None:
        return
    try:
        client.disconnect()
    except Exception:
        pass


def _read_current_config() -> Dict[str, Any]:
    _ensure_dirs()
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, dict):
                return data
        except (json.JSONDecodeError, OSError):
            pass
    return {}


def _env_value(key: str) -> Optional[str]:
    value = os.environ.get(key)
    if value:
        value = value.strip()
        return value or None
    return None


def load_visible_config() -> Dict[str, Any]:
    """Return configuration values suitable for the setup page."""
    current = _read_current_config()
    token = current.get("TOKEN") or _env_value("TOKEN") or ""
    api_id = current.get("ID") or _env_value("ID") or ""
    api_hash = current.get("HASH") or _env_value("HASH") or ""
    session_string = current.get("STRING") or _env_value("STRING") or ""

    masked = ""
    if session_string:
        if len(session_string) <= 12:
            masked = "*" * min(len(session_string), 4)
        else:
            masked = session_string[:4] + "..." + session_string[-4:]

    return {
        "token": token,
        "api_id": api_id,
        "api_hash": api_hash,
        "has_session": bool(session_string),
        "session_masked": masked,
    }


def save_configuration(
    token: str,
    api_id: str,
    api_hash: str,
    session_string: Optional[str] = None,
    preserve_existing_session: bool = False,
) -> Dict[str, Any]:
    """Persist bot credentials to both ``.env`` and ``config.json``."""
    _ensure_dirs()

    token = (token or "").strip()
    api_id = (api_id or "").strip()
    api_hash = (api_hash or "").strip()
    session_string = (session_string or "").strip()

    current = _read_current_config()
    existing_session = current.get("STRING") or _env_value("STRING") or ""

    if preserve_existing_session and not session_string and existing_session:
        session_string = existing_session

    env_lines = [
        "# Telegram Bot Configuration",
        "# Auto-generated by the Save-Restricted-Bot web setup",
        "",
        f"TOKEN={token}",
        "",
        f"ID={api_id}",
        "",
        f"HASH={api_hash}",
        "",
        f"STRING={session_string}",
        "",
        "TZ=Asia/Shanghai",
        "",
    ]
    with open(ENV_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(env_lines))

    config_data = {
        "TOKEN": token,
        "ID": api_id,
        "HASH": api_hash,
        "STRING": session_string or None,
    }
    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        json.dump(config_data, f, indent=4, ensure_ascii=False)

    return {
        "token": token,
        "api_id": api_id,
        "api_hash": api_hash,
        "has_session": bool(session_string),
        "session_masked": _mask_session(session_string),
    }


def _mask_session(session_string: str) -> str:
    if not session_string:
        return ""
    if len(session_string) <= 12:
        return "*" * min(len(session_string), 4)
    return session_string[:4] + "..." + session_string[-4:]


def _request_client_restart() -> None:
    """Ask the running bot/user clients to stop so the background loop reloads config."""
    try:
        from bot.handlers.instances import stop_and_clear_instances
        stop_and_clear_instances()
    except Exception:
        pass


def _cleanup_state(setup_id: str) -> None:
    with _setup_lock:
        state = _setup_states.pop(setup_id, None)
    _disconnect_state_client(state)


def _disconnect_state_client(state: Optional[Dict[str, Any]]) -> None:
    if not state:
        return
    client = state.get("client")
    if client is not None:
        _disconnect_auth_client(client)
    session_name = state.get("session_name")
    if session_name:
        _remove_session_files(session_name)


def _cleanup_all_setup_states() -> None:
    with _setup_lock:
        states = list(_setup_states.values())
        _setup_states.clear()
    for state in states:
        _disconnect_state_client(state)


def _get_state(setup_id: str) -> Optional[Dict[str, Any]]:
    with _setup_lock:
        return _setup_states.get(setup_id)


def start_session_auth(
    token: str,
    api_id: str,
    api_hash: str,
    phone_number: str,
) -> Dict[str, Any]:
    """Request a Telegram login code and store the active auth session."""
    _ensure_event_loop()
    _ensure_dirs()

    try:
        api_id_int = int(str(api_id).strip())
    except (TypeError, ValueError):
        return {"error": "API ID 必须是纯数字"}

    phone_number = (phone_number or "").strip()
    api_hash = (api_hash or "").strip()
    token = (token or "").strip()

    if not phone_number:
        return {"error": "手机号不能为空"}
    if not api_hash:
        return {"error": "API Hash 不能为空"}
    if not token:
        return {"error": "Bot Token 不能为空"}

    try:
        from pyrogram import Client
    except Exception as exc:
        return {"error": f"Pyrogram 未安装或无法加载: {exc}"}

    _cleanup_all_setup_states()

    setup_id = uuid.uuid4().hex
    session_name = f"web_auth_{setup_id}"
    client = None

    try:
        client = Client(
            session_name,
            api_id=api_id_int,
            api_hash=api_hash,
            phone_number=phone_number,
            workdir=SESSION_DIR,
            in_memory=False,
        )
        client.connect()
        sent_code = client.send_code(phone_number)
        phone_code_hash = getattr(sent_code, "phone_code_hash", None)
        if not phone_code_hash:
            _disconnect_auth_client(client)
            _remove_session_files(session_name)
            return {"error": "Telegram 未返回验证码哈希，请重试"}
    except Exception as exc:
        _disconnect_auth_client(client)
        _remove_session_files(session_name)
        return {"error": _friendly_pyrogram_error(exc)}

    with _setup_lock:
        _setup_states[setup_id] = {
            "session_name": session_name,
            "phone_number": phone_number,
            "phone_code_hash": phone_code_hash,
            "token": token,
            "api_id": str(api_id_int),
            "api_hash": api_hash,
            "stage": "code",
            "two_factor": False,
            "client": client,
        }

    return {
        "setup_id": setup_id,
        "stage": "code",
        "phone_number": phone_number,
    }


def submit_code(setup_id: str, code: str) -> Dict[str, Any]:
    """Submit a Telegram login code and advance the auth state machine."""
    _ensure_event_loop()
    _ensure_dirs()

    state = _get_state(setup_id)
    if not state:
        return {"error": "登录流程不存在或已过期，请重新开始"}

    client = state.get("client")
    if client is None or not getattr(client, "is_connected", False):
        _cleanup_state(setup_id)
        return {"error": "登录流程不存在或已过期，请重新开始"}

    code = (code or "").strip()
    if not code:
        return {
            "stage": "code",
            "setup_id": setup_id,
            "error": "验证码不能为空",
        }

    try:
        from pyrogram.errors import SessionPasswordNeeded
    except Exception as exc:
        return {
            "stage": "code",
            "setup_id": setup_id,
            "error": f"Pyrogram 未安装或无法加载: {exc}",
        }

    try:
        client.sign_in(
            state["phone_number"],
            state["phone_code_hash"],
            code,
        )
    except SessionPasswordNeeded:
        state["stage"] = "password"
        return {
            "stage": "password",
            "setup_id": setup_id,
            "message": "账号已开启两步验证，请输入两步验证密码",
        }
    except Exception as exc:
        return {
            "stage": "code",
            "setup_id": setup_id,
            "error": _friendly_pyrogram_error(exc),
        }

    try:
        session_string = client.export_session_string()
    except Exception as exc:
        _cleanup_state(setup_id)
        return {
            "stage": "code",
            "setup_id": setup_id,
            "error": f"导出 Session String 失败: {exc}",
        }
    else:
        _cleanup_state(setup_id)

    saved = save_configuration(
        state["token"],
        state["api_id"],
        state["api_hash"],
        session_string=session_string,
        preserve_existing_session=False,
    )
    _request_client_restart()
    return {
        "stage": "done",
        "session_string": session_string,
        "saved": saved,
        "message": "Session String 已自动生成并写入配置",
    }


def submit_password(setup_id: str, password: str) -> Dict[str, Any]:
    """Complete two-factor authentication and export the session string."""
    _ensure_event_loop()
    _ensure_dirs()

    state = _get_state(setup_id)
    if not state:
        return {"error": "登录流程不存在或已过期，请重新开始"}

    client = state.get("client")
    if client is None or not getattr(client, "is_connected", False):
        _cleanup_state(setup_id)
        return {"error": "登录流程不存在或已过期，请重新开始"}

    password = password or ""
    if not password.strip():
        return {
            "stage": "password",
            "setup_id": setup_id,
            "error": "两步验证密码不能为空",
        }

    try:
        client.check_password(password)
    except Exception as exc:
        return {
            "stage": "password",
            "setup_id": setup_id,
            "error": _friendly_pyrogram_error(exc),
        }

    try:
        session_string = client.export_session_string()
    except Exception as exc:
        _cleanup_state(setup_id)
        return {
            "stage": "password",
            "setup_id": setup_id,
            "error": f"导出 Session String 失败: {exc}",
        }
    else:
        _cleanup_state(setup_id)

    saved = save_configuration(
        state["token"],
        state["api_id"],
        state["api_hash"],
        session_string=session_string,
        preserve_existing_session=False,
    )
    _request_client_restart()
    return {
        "stage": "done",
        "session_string": session_string,
        "saved": saved,
        "message": "Session String 已自动生成并写入配置",
    }


def _friendly_pyrogram_error(exc: Exception) -> str:
    name = exc.__class__.__name__
    message = str(exc)

    if name == "PhoneCodeInvalid":
        return "验证码不正确，请检查后重新输入"
    if name == "PhoneCodeExpired":
        return "验证码已过期，请重新获取验证码"
    if name == "PhoneCodeEmpty":
        return "验证码为空"
    if name == "SessionPasswordNeeded":
        return "需要输入两步验证密码"
    if name == "FloodWait":
        wait = ""
        try:
            wait = str(getattr(exc, "value", "") or getattr(exc, "seconds", "") or "")
        except Exception:
            pass
        return f"Telegram 触发限流，请等待 {wait} 秒后重试"
    if name == "ApiIdInvalid":
        return "API ID 无效"
    if name == "PhoneNumberInvalid":
        return "手机号格式无效，请使用带国家代码的格式，例如 +8613800138000"
    if name == "PhoneNumberBanned":
        return "该手机号已被 Telegram 限制"
    if name == "PasswordHashInvalid":
        return "两步验证密码不正确"

    if "AUTH_KEY_UNREGISTERED" in message or "api_id" in message.lower():
        return "API 凭据错误，请检查 API ID 和 API Hash"
    if "PHONE_NUMBER_INVALID" in message:
        return "手机号格式无效，请使用带国家代码的格式，例如 +8613800138000"
    if "PHONE_CODE_INVALID" in message:
        return "验证码不正确"
    if "PHONE_CODE_EXPIRED" in message:
        return "验证码已过期"
    if "SESSION_PASSWORD_NEEDED" in message:
        return "需要输入两步验证密码"
    if "FLOOD_WAIT" in message:
        return "请求过于频繁，请稍后重试"

    return f"登录失败: {message or name}"
